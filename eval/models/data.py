"""The router's dataset: load Synapse v3's labelled questions, audit them, and write small derived files.

Provenance: the questions and their labels come from Azimlearning/GenUI-Education, `Synapse-V3/ml/router-distill/dataset/clean/{train,test}.jsonl`
at commit 835a2cefda285b4282ea4d0dbf986d1ff08abdb2. They were generated by an LLM teacher (no textbook text). Topic names come from
`data/kssm_topics.json` (ported in P0). This file is a re-implementation, not a copy.

    uv run python eval/models/data.py build      # read the v3 clone, audit, write data/models/router/*.jsonl and audit.json
    uv run python eval/models/data.py check      # re-run the audit on the derived files and print it

Heads (what the router predicts): topic (53 syllabus topics plus `none`), domain, pattern (v3's `artifact_type`), complexity.
"""

from __future__ import annotations

import json
import os
import random
import re
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DERIVED = REPO / "data" / "models" / "router"
TAXONOMY = REPO / "data" / "kssm_topics.json"
DEFAULT_SOURCE = Path("/home/user/azimlearning/genui-education/Synapse-V3/ml/router-distill/dataset/clean")
SOURCE_COMMIT = "835a2cefda285b4282ea4d0dbf986d1ff08abdb2"
SEED = 20261016
VAL_FRACTION = 0.15
NEAR_DUPLICATE_JACCARD = 0.8
HEADS = ("topic", "domain", "pattern", "complexity")
NONE = "none"


def taxonomy_slugs() -> list[str]:
    topics = json.loads(TAXONOMY.read_text(encoding="utf-8"))["topics"]
    return sorted(f"{t['subject']}_form{t['form']}_{t['slug']}" for t in topics)


def normalise(text: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9 ]+", " ", text.lower())).strip()


def tokens(text: str) -> frozenset[str]:
    return frozenset(normalise(text).split())


def jaccard(a: frozenset[str], b: frozenset[str]) -> float:
    return len(a & b) / len(a | b) if a and b else 0.0


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def to_row(raw: dict, slugs: set[str]) -> tuple[dict, str]:
    """A v3 row as ours, plus a status: ok, untagged (topic `none`), or stale (topic unknown to the taxonomy)."""
    tag = raw.get("curriculum_topic")
    if tag is None:
        topic, status = NONE, "untagged"
    elif tag in slugs:
        topic, status = tag, "ok"
    else:
        topic, status = None, "stale"
    return (
        {
            "query": raw["query"].strip(),
            "topic": topic,
            "domain": raw["domain"],
            "pattern": raw["artifact_type"],
            "complexity": int(raw["complexity"]),
        },
        status,
    )


def audit_and_split(train_raw: list[dict], test_raw: list[dict]) -> tuple[dict[str, list[dict]], dict]:
    slugs = set(taxonomy_slugs())
    audit: dict = {"source_commit": SOURCE_COMMIT, "seed": SEED, "taxonomy_topics": len(slugs)}

    def convert(rows: list[dict]) -> tuple[list[dict], Counter]:
        out, status = [], Counter()
        for raw in rows:
            row, st = to_row(raw, slugs)
            status[st] += 1
            out.append(row)
        return out, status

    train, train_status = convert(train_raw)
    test, test_status = convert(test_raw)
    audit["rows_in"] = {"train": len(train), "test": len(test)}
    audit["topic_status"] = {"train": dict(train_status), "test": dict(test_status)}

    # Exact duplicates inside train (keep the first), then train rows that duplicate or nearly duplicate a test row.
    seen: set[str] = set()
    deduped = []
    for row in train:
        key = normalise(row["query"])
        if key in seen:
            continue
        seen.add(key)
        deduped.append(row)
    audit["exact_duplicates_removed_from_train"] = len(train) - len(deduped)

    test_tokens = [tokens(r["query"]) for r in test]
    test_exact = {normalise(r["query"]) for r in test}
    clean_train, leaked_exact, leaked_near = [], 0, 0
    for row in deduped:
        if normalise(row["query"]) in test_exact:
            leaked_exact += 1
            continue
        t = tokens(row["query"])
        if any(jaccard(t, other) >= NEAR_DUPLICATE_JACCARD for other in test_tokens):
            leaked_near += 1
            continue
        clean_train.append(row)
    audit["train_rows_removed_for_test_leakage"] = {
        "exact": leaked_exact,
        "near": leaked_near,
        "threshold": NEAR_DUPLICATE_JACCARD,
    }

    # Stratified validation split: by topic when the topic is known, else by domain; a fixed seed.
    rng = random.Random(SEED)
    groups: dict[str, list[dict]] = {}
    for row in clean_train:
        groups.setdefault(row["topic"] or f"stale:{row['domain']}", []).append(row)
    train_out, val_out = [], []
    for key in sorted(groups):
        members = sorted(groups[key], key=lambda r: r["query"])
        rng.shuffle(members)
        n_val = max(1, round(len(members) * VAL_FRACTION)) if len(members) >= 4 else 0
        val_out += members[:n_val]
        train_out += members[n_val:]
    train_out.sort(key=lambda r: r["query"])
    val_out.sort(key=lambda r: r["query"])
    test.sort(key=lambda r: r["query"])
    audit["rows_out"] = {"train": len(train_out), "val": len(val_out), "test": len(test)}
    for head in HEADS:
        audit.setdefault("class_counts", {})[head] = {
            split: dict(
                sorted(Counter(r[head] for r in rows if r[head] is not None).items(), key=lambda kv: str(kv[0]))
            )
            for split, rows in (("train", train_out), ("val", val_out), ("test", test))
        }
    audit["topic_classes_in_train"] = len({r["topic"] for r in train_out if r["topic"] not in (None, NONE)})
    audit["topic_unknown_label_rows"] = {
        "train": sum(r["topic"] is None for r in train_out),
        "val": sum(r["topic"] is None for r in val_out),
        "test": sum(r["topic"] is None for r in test),
    }
    return {"train": train_out, "val": val_out, "test": test}, audit


def write_derived(splits: dict[str, list[dict]], audit: dict) -> None:
    DERIVED.mkdir(parents=True, exist_ok=True)
    for name, rows in splits.items():
        text = "".join(json.dumps(r, sort_keys=True, ensure_ascii=False) + "\n" for r in rows)
        (DERIVED / f"{name}.jsonl").write_text(text, encoding="utf-8")
    (DERIVED / "audit.json").write_text(json.dumps(audit, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def load_split(name: str) -> list[dict]:
    return read_jsonl(DERIVED / f"{name}.jsonl")


def leakage_between(a: list[dict], b: list[dict]) -> int:
    keys = {normalise(r["query"]) for r in a}
    return sum(normalise(r["query"]) in keys for r in b)


def main(argv: list[str]) -> int:
    command = argv[1] if len(argv) > 1 else "check"
    if command == "build":
        source = Path(os.environ.get("ROUTER_DATA_DIR", DEFAULT_SOURCE))
        splits, audit = audit_and_split(read_jsonl(source / "train.jsonl"), read_jsonl(source / "test.jsonl"))
        write_derived(splits, audit)
        print(json.dumps({k: v for k, v in audit.items() if k != "class_counts"}, indent=2, sort_keys=True))
        return 0
    print((DERIVED / "audit.json").read_text(encoding="utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
