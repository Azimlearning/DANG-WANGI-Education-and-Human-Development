"""Build every Bahasa Melayu overlay into a verified Environment, deliver it through the gate, and write the list (W12, D-62).

    uv run python -m eval.i18n.build_translations                 # all overlays; about 15 seconds each
    uv run python -m eval.i18n.build_translations newton_cannonball   # just these Plan ids

Free: no model call. Each Malay Environment goes through the plan checks (with the Malay copy budget), the deterministic assembler in Malay, the full verifier in real
Chromium and the delivery gate, exactly like the English one; with the local corpus (`CORPUS_DIR`) it is `kit-verified` when the English one is. The report holds
counts and ids, never a quotation (hard constraint 13), and says how many translations are still drafts.
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from api import kitmanifest  # noqa: E402
from api.evidence.corpus import Corpus  # noqa: E402
from api.evidence.registry import CitationBook  # noqa: E402
from api.i18n import overlay as overlay_module  # noqa: E402
from api.kit import latest_version  # noqa: E402
from api.pipeline import library  # noqa: E402
from api.pipeline import plan as plan_module  # noqa: E402
from api.verify.gate import deliver  # noqa: E402
from api.verify.store import SqliteEnvironmentStore  # noqa: E402
from eval.environments.build import KIT, ORIGIN, PLANS, corpus_dir  # noqa: E402

REPORT = REPO / "refdocs" / "evidence" / "2026-10-27-w12-translations.md"


def build(only: set[str] | None, corpus_path: Path | None) -> list[dict]:
    version = latest_version(KIT)
    manifest = kitmanifest.load(KIT, version)
    book = evidence = None
    if corpus_path is not None:
        book = CitationBook.load(Corpus.load(corpus_path), corpus_path)
        evidence = book.evidence
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        store = SqliteEnvironmentStore(Path(tmp) / "envs.db")
        for path in sorted(PLANS.glob("*.json")):
            plan = plan_module.parse(path.read_text(encoding="utf-8"))
            if only is not None and plan.id not in only:
                continue
            overlay = overlay_module.load_for(plan.id)
            if overlay is None:
                continue
            english, _ = library.build_environment(
                plan, manifest, version=version, book=book, evidence=evidence, public_origin=ORIGIN, kit_dist=KIT, interaction_seconds=1.0
            )
            store.put_verified(english)
            malay = library.translate(
                store, plan, english, manifest, version=version, book=book, evidence=evidence, public_origin=ORIGIN, kit_dist=KIT, interaction_seconds=1.0
            )
            if malay is None:
                continue
            block = deliver(store, malay.env_id, public_origin=ORIGIN, kit_dist=KIT, evidence=evidence)
            rows.append(
                {
                    "plan": plan.id,
                    "title": block.title,
                    "english": english.label,
                    "label": block.label,
                    "status": overlay.status,
                    "strings": len(overlay.strings),
                    "grid_points": block.checked.gridPoints,
                    "reference_cases": block.checked.referenceCases,
                }
            )
            print(f"  {plan.id}: {block.label} ({overlay.status}, {len(overlay.strings)} strings)")
    return rows


def render(rows: list[dict]) -> str:
    drafts = sum(1 for r in rows if r["status"] == "draft")
    lines = ["| Plan | Malay title | English label | Malay label | Translation | Strings | Grid points | Reference cases |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['plan']} | {r['title']} | {r['english']} | {r['label']} | {r['status']} | {r['strings']} | {r['grid_points']} | {r['reference_cases']} |")
    return f"""# Bahasa Melayu Environments (W12)

> Generated by `uv run python -m eval.i18n.build_translations` (do not edit by hand). Kit {latest_version(KIT)}. Fakes only; no model call.
> **{len(rows)} translations, {drafts} still drafts.** Each was applied to its Plan by the overlay checks, passed the plan checks (Malay copy budget), the Malay assembler, the verifier in real
> Chromium and the delivery gate. A draft is written by the build assistant and is **not served** unless the server is set to show drafts; only a fluent reviewer's approval
> (`uv run python -m eval.i18n.tools import`) makes a translation public.

{chr(10).join(lines)}

## What this does and does not show

- It shows that a translated Plan is checked exactly like the English one: the same numbers, units, science models and reference values, with the Kit's own fixed words in Malay.
- It does not show that the Malay is good. Every `draft` row needs a person who teaches or studies KSSM science in Bahasa Melayu to read it; the trust label says nothing about the language.
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("plans", nargs="*", help="Plan ids (default: every overlay)")
    ap.add_argument("--corpus", type=Path, default=None)
    args = ap.parse_args(argv)
    rows = build(set(args.plans) or None, corpus_dir(args.corpus))
    if not args.plans:
        REPORT.write_text(render(rows), encoding="utf-8")
        print(f"wrote {REPORT.relative_to(REPO)}")
    print(f"{len(rows)} translations built and delivered")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
